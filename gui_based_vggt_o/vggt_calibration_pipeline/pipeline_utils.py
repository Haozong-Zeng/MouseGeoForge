def load_model(checkpoint_path: Path, device: torch.device) -> VGGTOmega:
    if not checkpoint_path.is_file():
        raise FileNotFoundError(
            f"Checkpoint not found: {checkpoint_path}. "
            "Download with: hf download facebook/VGGT-Omega vggt_omega_1b_512.pt --local-dir checkpoints"
        )
    model = VGGTOmega(enable_depth=False, enable_alignment=False).eval()
    state_dict = _torch_load_checkpoint(checkpoint_path)
    try:
        missing, unexpected = model.load_state_dict(state_dict, strict=False)
    except RuntimeError as exc:
        raise RuntimeError("Failed to load checkpoint as VGGT-Omega.") from exc
    if missing:
        raise RuntimeError("Checkpoint is missing required keys: " + ", ".join(missing[:10]))
    allowed_unexpected = ("dense_head.", "text_alignment_head.")
    unexpected_required = [k for k in unexpected if not k.startswith(allowed_unexpected)]
    if unexpected_required:
        raise RuntimeError("Checkpoint has unexpected keys: " + ", ".join(unexpected_required[:10]))
    return model.to(device)


def _torch_load_checkpoint(checkpoint_path: Path) -> dict[str, torch.Tensor]:
    try:
        state_dict = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
    except TypeError:
        state_dict = torch.load(checkpoint_path, map_location="cpu")
    if not isinstance(state_dict, dict):
        raise TypeError(f"Expected state_dict, got {type(state_dict).__name__}")
    return state_dict


