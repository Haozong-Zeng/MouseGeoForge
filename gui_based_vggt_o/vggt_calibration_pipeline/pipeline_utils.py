def parse_distortions(value: str) -> list[float]:
    coeffs = [float(p) for p in re.split(r"[, ]+", value.strip()) if p]
    if len(coeffs) not in (4, 5, 8):
        raise ValueError("Expected 4, 5, or 8 distortion coefficients")
    return coeffs


