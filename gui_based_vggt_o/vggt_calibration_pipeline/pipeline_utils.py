def intrinsics_for_output_sizes(
    pose_encoding: np.ndarray,
    output_sizes: Sequence[tuple[int, int]],
) -> np.ndarray:
    if pose_encoding.ndim != 2 or pose_encoding.shape[1] < 9:
        raise ValueError(f"Expected pose encoding shape (num_cameras, >=9), got {pose_encoding.shape}")
    fov_h = pose_encoding[:, 7].astype(np.float64)
    fov_w = pose_encoding[:, 8].astype(np.float64)
    intrinsics = np.zeros((len(output_sizes), 3, 3), dtype=np.float64)
    for idx, (width, height) in enumerate(output_sizes):
        fx = (width / 2.0) / np.tan(fov_w[idx] / 2.0)
        fy = (height / 2.0) / np.tan(fov_h[idx] / 2.0)
        intrinsics[idx] = np.array(
            [[fx, 0.0, width / 2.0], [0.0, fy, height / 2.0], [0.0, 0.0, 1.0]],
            dtype=np.float64,
        )
    return intrinsics


def extrinsics_to_rvec_tvec(
    extrinsics: np.ndarray,
    translation_scale: float,
) -> tuple[np.ndarray, np.ndarray]:
    if extrinsics.ndim != 3 or extrinsics.shape[1:] != (3, 4):
        raise ValueError(f"Expected extrinsics shape (num_cameras, 3, 4), got {extrinsics.shape}")
    rvecs = np.zeros((extrinsics.shape[0], 3), dtype=np.float64)
    tvecs = np.zeros((extrinsics.shape[0], 3), dtype=np.float64)
    for idx, extrinsic in enumerate(extrinsics):
        rvec, _ = cv2.Rodrigues(extrinsic[:3, :3].astype(np.float64))
        rvecs[idx] = rvec.reshape(3)
        tvecs[idx] = extrinsic[:3, 3].astype(np.float64) * translation_scale
    return rvecs, tvecs


def write_anipose_toml(
    output_path: Path,
    names: Sequence[str],
    sizes: Sequence[tuple[int, int]],
    matrices: np.ndarray,
    rvecs: np.ndarray,
    tvecs: np.ndarray,
    distortions: Sequence[float],
    fisheye: bool,
) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by vggt_calibration_pipeline",
        "# VGGT-Omega predicts camera poses and pinhole intrinsics, not lens distortion.",
        "",
    ]
    for idx, name in enumerate(names):
        lines.extend([
            f"[cam_{idx}]",
            f"name = {json.dumps(name)}",
            f"size = {_toml_array([int(sizes[idx][0]), int(sizes[idx][1])])}",
            f"matrix = {_toml_array(_finite_list(matrices[idx]))}",
            f"distortions = {_toml_array(_finite_list(distortions))}",
            f"rotation = {_toml_array(_finite_list(rvecs[idx]))}",
            f"translation = {_toml_array(_finite_list(tvecs[idx]))}",
        ])
        if fisheye:
            lines.append("fisheye = true")
        lines.append("")
    output_path.write_text("\n".join(lines), encoding="utf-8")


def _finite_list(values: Sequence[float] | np.ndarray) -> list:
    arr = np.asarray(values, dtype=np.float64)
    if not np.all(np.isfinite(arr)):
        raise ValueError("Calibration contains non-finite values")
    return arr.tolist()


def _toml_array(values: Sequence[object]) -> str:
    return json.dumps(values, allow_nan=False, separators=(", ", ": "))


