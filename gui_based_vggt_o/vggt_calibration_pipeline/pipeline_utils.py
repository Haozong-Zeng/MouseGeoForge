@dataclass(frozen=True)
class CameraCalibration:
    name: str
    rotation: np.ndarray
    translation: np.ndarray
    matrix: np.ndarray | None
    size: tuple[int, int] | None
    distortions: np.ndarray | None

    @property
    def center(self) -> np.ndarray:
        return -self.rotation.T @ self.translation


def _load_toml(path: Path) -> dict[str, Any]:
    if _toml_backend is None:
        raise RuntimeError("No TOML parser. Use Python 3.11+ or install the 'toml' package.")
    mode = "rb" if _toml_backend.__name__ == "tomllib" else "r"
    with path.open(mode) as fh:
        return _toml_backend.load(fh)


def _as_float_array(value: Any, shape_last: int | None = None) -> np.ndarray | None:
    if value is None:
        return None
    arr = np.asarray(value, dtype=np.float64)
    if shape_last is not None and (arr.ndim == 0 or arr.shape[-1] != shape_last):
        raise ValueError(f"Expected final dim {shape_last}, got shape {arr.shape}")
    return arr


def _rodrigues_to_matrix(vector: np.ndarray) -> np.ndarray:
    matrix, _ = cv2.Rodrigues(vector.reshape(3).astype(np.float64))
    return matrix.astype(np.float64)


def _euler_xyz_to_matrix(vector: np.ndarray) -> np.ndarray:
    x, y, z = vector.reshape(3).astype(np.float64)
    if np.max(np.abs(vector)) > 2 * math.pi:
        x, y, z = np.radians([x, y, z])
    cx, sx = math.cos(x), math.sin(x)
    cy, sy = math.cos(y), math.sin(y)
    cz, sz = math.cos(z), math.sin(z)
    rx = np.array([[1, 0, 0], [0, cx, -sx], [0, sx, cx]], dtype=np.float64)
    ry = np.array([[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]], dtype=np.float64)
    rz = np.array([[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]], dtype=np.float64)
    return rz @ ry @ rx


def parse_calibration(path: Path) -> dict[str, CameraCalibration]:
    data = _load_toml(path)
    cameras: dict[str, CameraCalibration] = {}
    for table_key, table_value in data.items():
        if not isinstance(table_value, dict):
            continue
        translation = _as_float_array(table_value.get("translation"), shape_last=3)
        if translation is None:
            continue
        if table_value.get("rotation") is not None:
            rotation = _rodrigues_to_matrix(_as_float_array(table_value["rotation"], shape_last=3))
        elif table_value.get("rotation_euler") is not None:
            rotation = _euler_xyz_to_matrix(_as_float_array(table_value["rotation_euler"], shape_last=3))
        else:
            continue
        matrix = _as_float_array(table_value.get("matrix"))
        if matrix is not None:
            matrix = matrix.reshape(3, 3)
        size_value = table_value.get("size")
        size = None
        if size_value is not None:
            size_arr = np.asarray(size_value, dtype=int).reshape(-1)
            if size_arr.size >= 2:
                size = (int(size_arr[0]), int(size_arr[1]))
        distortions = _as_float_array(table_value.get("distortions"))
        name = str(table_value.get("name", table_key))
        cameras[name] = CameraCalibration(
            name=name, rotation=rotation,
            translation=translation.reshape(3),
            matrix=matrix, size=size, distortions=distortions,
        )
    if not cameras:
        raise ValueError(f"No camera tables found in {path}")
    return cameras


def _rotation_geodesic_deg(a: np.ndarray, b: np.ndarray) -> float:
    value = np.clip((np.trace(a.T @ b) - 1.0) / 2.0, -1.0, 1.0)
    return float(np.degrees(np.arccos(value)))


def _optimal_scalar_scale(source: np.ndarray, target: np.ndarray) -> float:
    denom = float(np.sum(source * source))
    return 1.0 if denom <= 1e-12 else float(np.sum(source * target) / denom)


def _relative_camera_layout(cameras: dict[str, CameraCalibration], origin: str):
    orig = cameras[origin]
    relative = {}
    for name, cam in cameras.items():
        relative[name] = (cam.rotation @ orig.rotation.T, orig.rotation @ (cam.center - orig.center))
    return relative


def _intrinsic_metrics(gt, pred, names):
    fx_err, fy_err, fx_pct, fy_pct = [], [], [], []
    for name in names:
        gm, pm = gt[name].matrix, pred[name].matrix
        if gm is None or pm is None:
            continue
        fx_err.append(abs(float(pm[0, 0]) - float(gm[0, 0])))
        fy_err.append(abs(float(pm[1, 1]) - float(gm[1, 1])))
        if abs(float(gm[0, 0])) > 1e-12:
            fx_pct.append(abs(float(pm[0, 0]) - float(gm[0, 0])) / abs(float(gm[0, 0])) * 100)
        if abs(float(gm[1, 1])) > 1e-12:
            fy_pct.append(abs(float(pm[1, 1]) - float(gm[1, 1])) / abs(float(gm[1, 1])) * 100)

    def _mean(v):
        return float(np.mean(v)) if v else float("nan")

    return {
        "mean_fx_abs_error": _mean(fx_err),
        "mean_fy_abs_error": _mean(fy_err),
        "mean_fx_pct_error": _mean(fx_pct),
        "mean_fy_pct_error": _mean(fy_pct),
    }


def _metrics_for_origin(gt, pred, origin, threshold_deg, include_origin, scale_align):
    if origin not in gt or origin not in pred:
        return {"error": f"origin {origin!r} missing", "num_cameras": 0}
    gt_rel = _relative_camera_layout(gt, origin)
    pred_rel = _relative_camera_layout(pred, origin)
    common = sorted(set(gt_rel) & set(pred_rel))
    if not include_origin and origin in common:
        common.remove(origin)
    if not common:
        return {"error": f"no evaluable cameras for origin {origin!r}", "num_cameras": 0}
    gt_pts = np.vstack([gt_rel[n][1] for n in common])
    pred_pts = np.vstack([pred_rel[n][1] for n in common])
    scale = _optimal_scalar_scale(pred_pts, gt_pts) if scale_align else 1.0
    return {
        "ATE_RMSE": float(np.sqrt(np.mean(np.linalg.norm(gt_pts - pred_pts, axis=1) ** 2))),
        "ATE_RMSE_scaled": float(np.sqrt(np.mean(np.linalg.norm(gt_pts - pred_pts * scale, axis=1) ** 2))),
        "pred_translation_scale_to_gt": float(scale),
        f"Pose_AUC_{threshold_deg:g}deg": float(np.mean(
            np.array([_rotation_geodesic_deg(gt_rel[n][0], pred_rel[n][0]) for n in common]) <= threshold_deg
        )),
        "mean_rot_error": float(np.mean([_rotation_geodesic_deg(gt_rel[n][0], pred_rel[n][0]) for n in common])),
        "max_rot_error": float(np.max([_rotation_geodesic_deg(gt_rel[n][0], pred_rel[n][0]) for n in common])),
        "num_cameras": len(common),
        "used_cameras": common,
        "origin": origin,
    }


def evaluate_calibration(gt, pred, origin_spec="ALL", threshold_deg=5.0, include_origin=False, scale_align=True):
    common_all = sorted(set(gt) & set(pred))
    origins = common_all if origin_spec.strip().upper() == "ALL" else [
        n.strip() for n in origin_spec.split("/") if n.strip() and n.strip() in gt and n.strip() in pred
    ]
    per_origin = [_metrics_for_origin(gt, pred, o, threshold_deg, include_origin, scale_align) for o in origins]
    valid = [m for m in per_origin if m.get("num_cameras", 0) > 0 and "ATE_RMSE" in m]
    if not valid:
        return {"error": f"No valid origin from {origin_spec!r}", "num_cameras": 0,
                "tried_origins": origins, "skipped_gt": sorted(set(gt) - set(pred)),
                "skipped_pred": sorted(set(pred) - set(gt))}
    metric_names = ["ATE_RMSE", "ATE_RMSE_scaled", "pred_translation_scale_to_gt",
                    f"Pose_AUC_{threshold_deg:g}deg", "mean_rot_error", "max_rot_error", "num_cameras"]
    result: dict[str, Any] = {k: float(np.mean([m[k] for m in valid])) for k in metric_names if k in valid[0]}
    result["num_cameras"] = int(round(result["num_cameras"]))
    result.update({"tried_origins": origins, "skipped_gt": sorted(set(gt) - set(pred)),
                   "skipped_pred": sorted(set(pred) - set(gt)), "per_origin": valid})
    result.update(_intrinsic_metrics(gt, pred, common_all))
    return result


def collect_prediction_files(path: Path) -> list[Path]:
    if path.is_file():
        return [path]
    if not path.is_dir():
        raise FileNotFoundError(f"Prediction path not found: {path}")
    files = sorted(path.glob("frame_*/calibration.toml"))
    if not files:
        files = sorted(path.glob("calibration*.toml"))
    if not files:
        raise FileNotFoundError(f"No calibration files found in {path}")
    return files


def evaluate_prediction_files(
    ground_truth_path: Path,
    predictions_path: Path,
    threshold_deg: float = 5.0,
    origin_spec: str = "ALL",
    include_origin: bool = False,
    scale_align: bool = True,
) -> list[dict[str, Any]]:
    gt = parse_calibration(ground_truth_path)
    rows = []
    for prediction_path in collect_prediction_files(predictions_path):
        try:
            pred = parse_calibration(prediction_path)
            metrics = evaluate_calibration(gt, pred, origin_spec, threshold_deg, include_origin, scale_align)
        except Exception as exc:
            metrics = {"error": str(exc), "num_cameras": 0}
        row = {"file": prediction_path.name, "path": str(prediction_path),
               "note": metrics.get("error", ""),
               "tried_origins": ",".join(metrics.get("tried_origins", []) or []),
               "skipped_gt": ",".join(metrics.get("skipped_gt", []) or []),
               "skipped_pred": ",".join(metrics.get("skipped_pred", []) or [])}
        for key, value in metrics.items():
            if key not in {"per_origin", "error", "tried_origins", "skipped_gt", "skipped_pred"}:
                row[key] = value
        rows.append(row)
    return rows


def write_csv(rows: Sequence[dict[str, Any]], output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames: list[str] = []
    for row in rows:
        for key in row:
            if key not in fieldnames:
                fieldnames.append(key)
    with output_path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def write_summary(rows: Sequence[dict[str, Any]], output_path: Path) -> dict[str, Any]:
    valid = [r for r in rows if r.get("ATE_RMSE_scaled") not in (None, "") and not r.get("note")]
    summary: dict[str, Any] = {"num_predictions": len(rows), "num_valid": len(valid)}
    if valid:
        best = min(valid, key=lambda r: float(r["ATE_RMSE_scaled"]))
        summary["best_file"] = best.get("file")
        for key in ["ATE_RMSE", "ATE_RMSE_scaled", "pred_translation_scale_to_gt",
                    "mean_rot_error", "max_rot_error", "mean_fx_pct_error", "mean_fy_pct_error"]:
            values = [float(r[key]) for r in valid if key in r and np.isfinite(float(r[key]))]
            if values:
                summary[f"mean_{key}"] = float(np.mean(values))
                summary[f"min_{key}"] = float(np.min(values))
                summary[f"max_{key}"] = float(np.max(values))
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(summary, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    return summary


def maybe_plot(rows: Sequence[dict[str, Any]], output_path: Path) -> None:
    valid = [r for r in rows if r.get("ATE_RMSE_scaled") not in (None, "") and not r.get("note")]
    if not valid:
        return
    try:
        import matplotlib.pyplot as plt
    except Exception:
        return
    x = np.arange(len(valid))
    ate = np.array([float(r["ATE_RMSE_scaled"]) for r in valid])
    rot = np.array([float(r["mean_rot_error"]) for r in valid])
    fig, axes = plt.subplots(1, 2, figsize=(12, 4))
    axes[0].plot(x, ate, marker=".", linewidth=1)
    axes[0].set_title("Scale-aligned translation RMSE")
    axes[0].set_xlabel("Prediction index")
    axes[0].set_ylabel("RMSE")
    axes[0].grid(True, alpha=0.3)
    axes[1].plot(x, rot, marker=".", linewidth=1, color="#b85c38")
    axes[1].set_title("Mean relative rotation error")
    axes[1].set_xlabel("Prediction index")
    axes[1].set_ylabel("Degrees")
    axes[1].grid(True, alpha=0.3)
    fig.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=160)
    plt.close(fig)
